/// Minimal fixed-window per-IP failure counter (in-memory, per-process).
struct RateLimiter {
    // ip -> (failures in the current window, window start)
    failures: std::sync::Mutex<HashMap<IpAddr, (u32, Instant)>>,
}

impl RateLimiter {
    fn new() -> Self {
        Self { failures: std::sync::Mutex::new(HashMap::new()) }
    }

    /// Drop expired windows so attacker-controlled IP churn cannot grow the
    /// map without bound (memory-DoS guard).
    fn prune(&self, now: Instant) {
        let mut map = self.failures.lock().unwrap_or_else(|e| e.into_inner());
        map.retain(|_, (_, start)| now.duration_since(*start) <= LOGIN_WINDOW);
    }

    fn record_failure(&self, ip: IpAddr) {
        let now = Instant::now();
        self.prune(now);
        let mut map = self.failures.lock().unwrap_or_else(|e| e.into_inner());
        let entry = map.entry(ip).or_insert((0, now));
        if now.duration_since(entry.1) > LOGIN_WINDOW {
            *entry = (1, now);
        } else {
            entry.0 += 1;
        }
    }

    fn blocked(&self, ip: IpAddr) -> bool {
        let now = Instant::now();
        self.prune(now);
        let map = self.failures.lock().unwrap_or_else(|e| e.into_inner());
        map.get(&ip)
            .map(|(n, start)| *n >= LOGIN_MAX_FAILURES && now.duration_since(*start) <= LOGIN_WINDOW)
            .unwrap_or(false)
    }
}

fn login_limiter() -> &'static RateLimiter {
    static LIMITER: OnceLock<RateLimiter> = OnceLock::new();
    LIMITER.get_or_init(RateLimiter::new)
}

/// Constant-time string comparison via SHA-256 digests (lengths are equal
/// after hashing, so no length side-channel either).
///
/// [Note]
/// Implemented as a fixed-length accumulate-and-compare over 32 bytes: no
/// early exit on mismatch (ring::constant_time is deprecated in ring 0.17.14).
fn ct_str_eq(a: &str, b: &str) -> bool {
    use ring::digest::{digest, SHA256};
    let da = digest(&SHA256, a.as_bytes());
    let db = digest(&SHA256, b.as_bytes());
    let (a, b) = (da.as_ref(), db.as_ref());
    let mut diff = 0u8;
    for i in 0..a.len() {
        diff |= a[i] ^ b[i];
    }
    diff == 0
}

struct AdminAuth;

#[axum::async_trait]
impl axum::extract::FromRequestParts<SharedState> for AdminAuth {
    type Rejection = (StatusCode, String);

    async fn from_request_parts(
        parts: &mut axum::http::request::Parts,
        state: &SharedState,
    ) -> Result<Self, Self::Rejection> {
        let auth_header = parts
            .headers
            .get(axum::http::header::AUTHORIZATION)
            .and_then(|h| h.to_str().ok());

        let token = match auth_header {
            Some(h) if h.starts_with("Bearer ") => &h[7..],
            _ => return Err((StatusCode::UNAUTHORIZED, "Unauthorized".to_string())),
        };

        let conn = state.db.lock().map_err(|_| db_poisoned())?;
        match db::check_admin_token(&conn, token) {
            Ok(true) => Ok(AdminAuth),
            _ => Err((StatusCode::UNAUTHORIZED, "Unauthorized".to_string())),
        }
    }
}

/// Client API authentication: per-device token in `X-Device-Token`.
///
/// [Note]
/// Tokens are minted once by `register_client` for a NEW client id and only
/// the SHA-256 hash is stored, so a DB leak yields no usable credentials.
/// `identity` is the client id bound to the token; handlers serving
/// `/api/client/:id/*` must verify `identity == :id` (anti-IDOR).
///
/// Legacy escape hatch: when `DESKAGENT_CLIENT_TOKEN` is configured, a
/// matching `X-Client-Token` grants an UNBOUND identity (Any) — for fleet
/// migration only; the shared token does not restrict which :id it may act on.
///
/// Fail-closed: with no valid device token and no configured shared token,
/// every client/conversation request is rejected.
struct DeviceAuth {
    /// Some(client_id) = per-device identity; None = legacy shared token.
    identity: Option<String>,
}

impl DeviceAuth {
    fn is(&self, client_id: &str) -> bool {
        self.identity.as_deref() == Some(client_id)
    }
}

#[axum::async_trait]
impl axum::extract::FromRequestParts<SharedState> for DeviceAuth {
    type Rejection = (StatusCode, String);

    async fn from_request_parts(
        parts: &mut axum::http::request::Parts,
        state: &SharedState,
    ) -> Result<Self, Self::Rejection> {
        let header = |name: &str| {
            parts
                .headers
                .get(name)
                .and_then(|h| h.to_str().ok())
                .map(str::trim)
                .filter(|h| !h.is_empty())
        };
        let conn = state.db.lock().map_err(|_| db_poisoned())?;
        if let Some(tok) = header("X-Device-Token") {
            let hash = crate::crypto::hash_token(tok);
            match db::device_client_id(&conn, &hash) {
                Ok(Some(client_id)) => return Ok(DeviceAuth { identity: Some(client_id) }),
                _ => return Err((StatusCode::UNAUTHORIZED, "Unauthorized".to_string())),
            }
        }
        if !state.client_token.is_empty() {
            if let Some(tok) = header(CLIENT_TOKEN_HEADER) {
                if ct_str_eq(tok, &state.client_token) {
                    return Ok(DeviceAuth { identity: None });
                }
            }
        }
        Err((StatusCode::UNAUTHORIZED, "Unauthorized".to_string()))
    }
}

#[derive(Deserialize)]
struct LoginIn {
    username: String,
    password: String,
}


async fn login(
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    State(state): State<SharedState>,
    Json(payload): Json<LoginIn>,

) -> Result<Json<Value>, (StatusCode, String)> {
    // Brute-force guard: fixed window of failures per source IP.
    if login_limiter().blocked(peer.ip()) {
        return Err((
            StatusCode::TOO_MANY_REQUESTS,
            "Quá nhiều lần đăng nhập sai. Vui lòng thử lại sau.".to_string(),
        ));
    }
    // Constant-time compare to avoid a timing side-channel on the password.
    if ct_str_eq(&payload.username, &state.admin_user) && ct_str_eq(&payload.password, &state.admin_pass) {
        let token = new_id("tok_");
        let conn = state.db.lock().map_err(|_| db_poisoned())?;
        db::create_admin_token(&conn, &token).map_err(internal_error)?;
        // The auto-generated bootstrap password file is one-time: once an
        // admin has logged in, remove it so the credential does not linger
        // on disk.
        let _ = std::fs::remove_file(crate::BOOTSTRAP_PASS_FILE);
        Ok(Json(json!({ "ok": true, "token": token, "username": state.admin_user })))
    } else {
        login_limiter().record_failure(peer.ip());
        Err((StatusCode::UNAUTHORIZED, "Sai tên đăng nhập hoặc mật khẩu".to_string()))
    }
}

async fn logout(
    _auth: AdminAuth,
    State(state): State<SharedState>,
    headers: axum::http::HeaderMap,
) -> Result<Json<Value>, (StatusCode, String)> {
    if let Some(token) = headers
        .get(axum::http::header::AUTHORIZATION)
        .and_then(|h| h.to_str().ok())
        .and_then(|h| if h.starts_with("Bearer ") { Some(&h[7..]) } else { None })
    {
        if let Ok(conn) = state.db.lock() {
            let _ = db::delete_admin_token(&conn, token);
        }
    }
    Ok(Json(json!({ "ok": true })))
}

async fn auth_me(
    _auth: AdminAuth,
    State(state): State<SharedState>,
) -> Result<Json<Value>, (StatusCode, String)> {
    Ok(Json(json!({ "authenticated": true, "username": state.admin_user })))
}

