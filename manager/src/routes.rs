fn valid_mac(value: &str) -> bool {
    let parts: Vec<_> = value.split(':').collect();
    parts.len() == 6
        && parts.iter().all(|p| p.len() == 2 && p.chars().all(|c| c.is_ascii_hexdigit()))
        && parts[0].as_bytes().first().map(|b| b & 1 == 0).unwrap_or(false)
        && value != "00:00:00:00:00:00"
}

