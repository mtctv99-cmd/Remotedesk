async fn post_message(
    _auth: DeviceAuth,
    State(state): State<SharedState>,
    Path(id): Path<String>,
    Json(payload): Json<MsgIn>,
) -> Result<Json<Value>, (StatusCode, String)> {
    // Scope the lock: dropped before the AI call below.
    let (action, ai_cfg) = {
        let conn = state.db.lock().map_err(|_| db_poisoned())?;
        if !db::conversation_exists(&conn, &id).map_err(internal_error)? {
            return Err(not_found());
        }
        db::insert_message(&conn, &id, "user", &payload.text).map_err(internal_error)?;
        if db::is_conversation_claimed(&conn, &id).map_err(internal_error)? {
            (BotAction::Skip, None)
        } else {
            let (url, key, model, prompt) =
                db::get_effective_ai_config(&conn).map_err(internal_error)?;
            let cfg = ai::AiConfig::new(url, key, model, prompt);
            if !cfg.is_configured() {
                (BotAction::NotConfigured, None)
            } else {
                let mut history =
                    db::ai_history(&conn, &id, AI_HISTORY_CAP).map_err(internal_error)?;
                // Enrich the prompt with the bound client's machine context
                // (inventory snapshot + newest events) ahead of the history,
                // so the bot answers about THIS machine instead of guessing.
                if let Ok(Some(client_id)) = db::conversation_client_id(&conn, &id) {
                    if let Some(ctx) = build_ai_context(&conn, &client_id) {
                        history.insert(0, ("system".to_string(), ctx));
                    }
                }
                (BotAction::Ask(history), Some(cfg))
            }
        }
    };

    let reply = match action {
        BotAction::Skip => return Ok(Json(json!({ "reply": Value::Null }))),
        BotAction::NotConfigured => "chưa cấu hình AI".to_string(),
        BotAction::Ask(history) => match ai_cfg {
            Some(cfg) => match ai::chat_with_config(cfg, history).await {
                Ok(text) => text,
                // Do NOT store internal errors as bot messages: db::ai_history
                // feeds bot messages back as "assistant" context, so an
                // '[AI error: ...]' string would pollute the conversation
                // forever. Surface it as an HTTP error instead.
                Err(e) => {
                    return Err((
                        StatusCode::BAD_GATEWAY,
                        format!("AI request failed: {e}"),
                    ))
                }
            },
            None => "[AI error]".to_string(),
        },
    };

    let conn = state.db.lock().map_err(|_| db_poisoned())?;
    db::insert_message(&conn, &id, "bot", &reply).map_err(internal_error)?;
    Ok(Json(json!({ "reply": reply })))
}

