    use axum::body::Body;
    use axum::extract::ConnectInfo;
    use axum::http::Request;
    use tower::ServiceExt;

    fn peer(octets: [u8; 4], port: u16) -> SocketAddr {
        SocketAddr::new(std::net::IpAddr::V4(std::net::Ipv4Addr::from(octets)), port)
    }

    /// Run one request through the router. `ConnectInfo` is injected the same
    /// way `into_make_service_with_connect_info` does in production; the JSON
    /// response body is returned as a `Value` (Null for empty bodies).
    async fn oneshot_json(
        state: &SharedState,
        method: &str,
        uri: &str,
        headers: &[(&str, &str)],
        body: Option<Value>,
        peer_addr: SocketAddr,
    ) -> (StatusCode, Value) {
        let mut builder = Request::builder()
            .method(method)
            .uri(uri)
            .header("content-type", "application/json");
        for (h, v) in headers {
            builder = builder.header(*h, *v);
        }
        let mut req = builder
            .body(Body::from(body.map(|b| b.to_string()).unwrap_or_default()))
            .expect("build request");
        req.extensions_mut().insert(ConnectInfo(peer_addr));
        let resp = router(state.clone())
            .oneshot(req)
            .await
            .expect("router responds");
        let status = resp.status();
        let bytes = axum::body::to_bytes(resp.into_body(), usize::MAX)
            .await
            .expect("read body");
        let json = if bytes.is_empty() {
            Value::Null
        } else {
            serde_json::from_slice(&bytes).unwrap_or(Value::Null)
        };
        (status, json)
    }

    /// Login as the bootstrap admin and return the bearer token.
