/// Register a client and mint its device token.
///
/// [Note]
/// Anti-takeover rules (a register request is unauthenticated except for an
/// optionally presented `X-Device-Token`):
/// - Rows merge/adopt ONLY on a matching machine_id (MachineGuid read from the
///   local machine is the hardware proof).
/// - A hostname-only (pre-machine_id) row is adopted ONLY when the caller
///   presents the exact token bound to that row, or the row has NO device
///   token at all (a true legacy row).
/// - A presented token that binds a client which is neither the target row nor
///   a same-machine duplicate is a 403 and mints nothing. Clients treat 401
///   and 403 the same (drop identity, re-register fresh), so this never
///   locks a legitimate machine out.
/// - New client id (not in DB): create the row, mint a one-time device token
///   (returned in plaintext exactly once; only its SHA-256 hash is stored).
/// - Known client id WITHOUT a valid token: 401 — knowledge of a client id
///   must not be enough to take it over.
async fn register_client(
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    State(state): State<SharedState>,
    headers: axum::http::HeaderMap,
    Json(payload): Json<RegisterIn>,
) -> Result<Json<Value>, (StatusCode, String)> {
    // The socket peer address is authoritative; a client-supplied `ip` would
    // let any caller spoof another machine into the inventory/peer lists.
    let client_ip = peer.ip().to_string();
    let _ = payload.ip;
    let client_version = payload.version.clone().unwrap_or_default();
    let mac_address = payload
        .mac_address
        .as_deref()
        .map(str::trim)
        .filter(|s| valid_mac(s))
        .unwrap_or("")
        .to_owned();
    let machine_id = payload
        .machine_id
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .unwrap_or("")
        .to_owned();
    let conn = state.db.lock().map_err(|_| db_poisoned())?;

    let presented_token = headers
        .get("X-Device-Token")
        .and_then(|h| h.to_str().ok())
        .map(str::trim)
        .filter(|t| !t.is_empty())
        .map(str::to_owned);
    let presented_binds_to = match &presented_token {
        Some(tok) => db::device_client_id(&conn, &crate::crypto::hash_token(tok))
            .map_err(internal_error)?,
        None => None,
    };
    if presented_token.is_some() && presented_binds_to.is_none() {
        return Err((StatusCode::UNAUTHORIZED, "invalid device token".to_string()));
    }

    // Which row is THE row for this machine?
    let target_id = if !machine_id.is_empty() {
        if let Some(canonical) =
            db::find_canonical_client(&conn, &machine_id).map_err(internal_error)?
        {
            // An existing row carries this machine_id. A presented token may
            // bind the canonical row itself (heartbeat) or a same-machine
            // duplicate that is about to be collapsed into it — anything else
            // is an unrelated client and must not yield a token for this row.
            if let Some(bound) = &presented_binds_to {
                if bound != &canonical {
                    let bound_machine = db::client_machine_id(&conn, bound)
                        .map_err(internal_error)?
                        .unwrap_or_default();
                    if bound_machine != machine_id {
                        return Err((
                            StatusCode::FORBIDDEN,
                            "device token bound to another client".to_string(),
                        ));
                    }
                }
            }
            canonical
        } else if let Some(legacy_id) =
            db::find_hostname_only_client(&conn, &payload.hostname).map_err(internal_error)?
        {
            // Hostname-only row: adopt only under the two safe conditions.
            let bound_matches =
                presented_binds_to.as_deref() == Some(legacy_id.as_str());
            let adoptable = bound_matches
                || !db::client_has_device_token(&conn, &legacy_id)
                    .map_err(internal_error)?;
            if adoptable {
                legacy_id
            } else {
                // Row belongs to an authenticated client we cannot prove;
                // never hand out a token for it via a hostname match alone.
                fresh_register_target(&conn, &payload, &presented_binds_to)?
            }
        } else {
            fresh_register_target(&conn, &payload, &presented_binds_to)?
        }
    } else {
        // Legacy client that does not report a machine_id: no merging, the
        // row must be taken over by its own token only.
        if db::client_exists(&conn, &payload.client_id).map_err(internal_error)? {
            match &presented_binds_to {
                None => {
                    return Err((
                        StatusCode::UNAUTHORIZED,
                        "client already registered; device token required".to_string(),
                    ))
                }
                Some(bound) if bound == &payload.client_id => {} // heartbeat
                Some(_) => {
                    return Err((
                        StatusCode::FORBIDDEN,
                        "device token bound to another client".to_string(),
                    ))
                }
            }
        }
        payload.client_id.clone()
    };

    db::upsert_client(
        &conn,
        &target_id,
        &payload.hostname,
        &payload.os,
        &payload.os_version,
        &payload.arch,
        &client_ip,
        &client_version,
        &machine_id,
        &mac_address,
    )
    .map_err(internal_error)?;
    if !machine_id.is_empty() {
        let removed = db::delete_duplicate_clients(&conn, &target_id, &machine_id)
            .map_err(internal_error)?;
        if removed > 0 {
            eprintln!(
                "register: collapsed {} duplicate row(s) of machine {:?} into {}",
                removed,
                payload.hostname,
                target_id
            );
        }
    }
    // Self-prune rows that have been gone for more than 30 days (safe: the
    // row we just touched has a fresh last_seen and is never a victim).
    match db::prune_stale_clients(&conn) {
        Ok(n) if n > 0 => eprintln!("register: pruned {n} stale client row(s) (>30 days)"),
        Ok(_) => {}
        Err(e) => eprintln!("register: stale-client prune failed: {e}"),
    }

    // Token bookkeeping: when the presented token already binds to the target
    // row the caller is authenticated as-is. Otherwise (fresh register, or the
    // caller's identity was just merged away) mint a new token bound to the
    // canonical row and hand it back so the client re-anchors itself.
    if presented_binds_to.as_deref() == Some(target_id.as_str()) {
        return Ok(Json(json!({ "ok": true, "client_id": target_id, "mac_address": mac_address })));
    }
    let rng = SystemRandom::new();
    let mut bytes = [0u8; 32];
    rng.fill(&mut bytes).map_err(|_| internal_error("CSPRNG failure"))?;
    let mut tok = String::with_capacity(64 + 3);
    tok.push_str("dt_");
    for b in bytes {
        let _ = write!(tok, "{b:02x}");
    }
    db::create_device_token(&conn, &crate::crypto::hash_token(&tok), &target_id)
        .map_err(internal_error)?;
    Ok(Json(json!({ "ok": true, "device_token": tok, "client_id": target_id, "mac_address": mac_address })))
}

/// Target resolution for a register that found no machine/hostname row to
/// adopt: a brand-new client id, or the caller's own row (heartbeat). A known
/// id requires its own token — 401 without one, 403 with someone else's.
fn fresh_register_target(
    conn: &rusqlite::Connection,
    payload: &RegisterIn,
    presented_binds_to: &Option<String>,
) -> Result<String, (StatusCode, String)> {
    if db::client_exists(conn, &payload.client_id).map_err(internal_error)? {
        match presented_binds_to {
            None => {
                return Err((
                    StatusCode::UNAUTHORIZED,
                    "client already registered; device token required".to_string(),
                ))
            }
            Some(bound) if bound == &payload.client_id => {} // heartbeat
            Some(_) => {
                return Err((
                    StatusCode::FORBIDDEN,
                    "device token bound to another client".to_string(),
                ))
            }
        }
    }
    Ok(payload.client_id.clone())
}

