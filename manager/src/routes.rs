    #[tokio::test]
    async fn client_jobs_claim_lease_and_result_flow() {
        let state = test_state();
        let client_p = peer([10, 110, 0, 3], 40102);
        let admin_p = peer([10, 110, 0, 4], 40103);

        let (_, v) = register(&state, "c-jobs-1", "1.0.0", client_p).await;
        let token = v["device_token"].as_str().expect("device token").to_string();
        let admin = admin_login(&state, admin_p).await;
        let bearer = format!("Bearer {admin}");
        let auth_header: (&str, &str) = ("Authorization", bearer.as_str());
        let token_header: (&str, &str) = ("X-Device-Token", token.as_str());

        // Admin creates a cmd-only job (no package_url/package_path).
        let (status, v) = oneshot_json(
            &state,
            "POST",
            "/api/admin/jobs",
            &[auth_header],
            Some(json!({ "client_id": "c-jobs-1", "silent_cmd": "cmd /c echo hi" })),
            admin_p,
        )
        .await;
        assert_eq!(status, StatusCode::OK, "create job: {v}");
        let job_id = v["job_id"].as_str().expect("job id").to_string();
        assert!(!v["signature"].as_str().unwrap_or_default().is_empty());

        // Client polls: the job is delivered CLAIMED (status 'running') with a
        // lease, and package fields are EMPTY STRINGS — never JSON null (older
        // clients fail to parse null).
        let (status, v) = oneshot_json(
            &state,
            "GET",
            &format!("/api/client/c-jobs-1/jobs"),
            &[token_header],
            None,
            client_p,
        )
        .await;
        assert_eq!(status, StatusCode::OK, "client jobs: {v}");
        let jobs = v.as_array().expect("bare job array").clone();
        assert_eq!(jobs.len(), 1, "job delivered once");
        assert_eq!(jobs[0]["id"], json!(job_id));
        assert_eq!(jobs[0]["status"], json!("running"), "delivered claimed");
        assert_eq!(jobs[0]["package_url"], json!(""), "null breaks old clients");
        assert_eq!(jobs[0]["package_path"], json!(""), "null breaks old clients");
        assert!(jobs[0]["package_url"].is_string());

        // Lease held: an immediate re-poll returns nothing.
        let (status, v) = oneshot_json(
            &state,
            "GET",
            "/api/client/c-jobs-1/jobs",
            &[token_header],
            None,
            client_p,
        )
        .await;
        assert_eq!(status, StatusCode::OK);
        assert!(v.as_array().expect("bare job array").is_empty(), "lease held: {v}");

        // Results are scoped to the owning client and terminal statuses only.
        let (status, _) = oneshot_json(
            &state,
            "POST",
            &format!("/api/client/c-jobs-1/jobs/{job_id}/result"),
            &[token_header],
            Some(json!({ "status": "pending", "output": "x" })),
            client_p,
        )
        .await;
        assert_eq!(status, StatusCode::BAD_REQUEST, "non-terminal status rejected");

        let (status, _) = oneshot_json(
            &state,
            "POST",
            &format!("/api/client/c-jobs-1/jobs/unknown-job/result"),
            &[token_header],
            Some(json!({ "status": "success", "output": "x" })),
            client_p,
        )
        .await;
        assert_eq!(status, StatusCode::NOT_FOUND, "foreign job id rejected");

        let (status, v) = oneshot_json(
            &state,
            "POST",
            &format!("/api/client/c-jobs-1/jobs/{job_id}/result"),
            &[token_header],
            Some(json!({ "status": "success", "output": "hi" })),
            client_p,
        )
        .await;
        assert_eq!(status, StatusCode::OK, "report result: {v}");

        // Admin sees the result and the terminal status.
        let (status, v) = oneshot_json(
            &state,
            "GET",
            "/api/admin/jobs",
            &[auth_header],
            None,
            admin_p,
        )
        .await;
        assert_eq!(status, StatusCode::OK);
        let jobs = v.as_array().expect("jobs array");
        assert_eq!(jobs[0]["status"], json!("success"));
        assert_eq!(jobs[0]["result"]["output"], json!("hi"));

        // Another client cannot report on this job (anti-IDOR).
        let (_, v2) = register(&state, "c-jobs-2", "1.0.0", client_p).await;
        let token2 = v2["device_token"].as_str().unwrap().to_string();
        let (status, _) = oneshot_json(
            &state,
            "POST",
            &format!("/api/client/c-jobs-2/jobs/{job_id}/result"),
            &[("X-Device-Token", token2.as_str())],
            Some(json!({ "status": "success", "output": "hijack" })),
            client_p,
        )
        .await;
        assert_eq!(status, StatusCode::NOT_FOUND, "foreign client rejected");
    }

