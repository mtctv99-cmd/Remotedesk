async fn admin_save_settings(
    _auth: AdminAuth,
    State(state): State<SharedState>,
    Json(payload): Json<SettingsIn>,
) -> Result<Json<Value>, (StatusCode, String)> {
    if let Some(ref url) = payload.ai_url {
        let trimmed = url.trim();
        if !trimmed.is_empty() {
            ai::validate_outbound_url(trimmed).map_err(|e| (StatusCode::BAD_REQUEST, e))?;
        }
    }

    let conn = state.db.lock().map_err(|_| db_poisoned())?;

    if let Some(url) = payload.ai_url {
        db::set_setting(&conn, "ai_url", url.trim()).map_err(internal_error)?;
    }
    if let Some(key) = payload.ai_key {
        let trimmed = key.trim();
        if !trimmed.is_empty() {
            db::set_setting(&conn, "ai_key", trimmed).map_err(internal_error)?;
        }
    }
    if let Some(model) = payload.ai_model {
        db::set_setting(&conn, "ai_model", model.trim()).map_err(internal_error)?;
    }
    if let Some(prompt) = payload.ai_prompt {
        db::set_setting(&conn, "ai_prompt", prompt.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.rendezvous_server {
        db::set_setting(&conn, "rendezvous_server", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.relay_server {
        db::set_setting(&conn, "relay_server", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.server_key {
        db::set_setting(&conn, "server_key", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.deploy_pubkey {
        db::set_setting(&conn, "deploy_pubkey", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.custom_fps {
        db::set_setting(&conn, "custom_fps", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.image_quality {
        db::set_setting(&conn, "image_quality", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.codec_preference {
        db::set_setting(&conn, "codec_preference", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.direct_server {
        db::set_setting(&conn, "direct_server", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.enable_lan_discovery {
        db::set_setting(&conn, "enable_lan_discovery", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.allow_wan {
        db::set_setting(&conn, "allow_wan", s.trim()).map_err(internal_error)?;
    }
    if let Some(s) = payload.vlan_subnets {
        db::set_setting(&conn, "vlan_subnets", s.trim()).map_err(internal_error)?;
    }
    if let Some(ref s) = payload.update_latest {
        db::set_setting(&conn, "update_latest", s.trim()).map_err(internal_error)?;
    }
    if let Some(ref s) = payload.update_min_supported {
        db::set_setting(&conn, "update_min_supported", s.trim()).map_err(internal_error)?;
    }
    if let Some(ref s) = payload.update_url {
        let t = s.trim();
        if !t.is_empty() && !t.starts_with('/') {
            ai::validate_outbound_url(t).map_err(|e| (StatusCode::BAD_REQUEST, e))?;
        }
        db::set_setting(&conn, "update_url", t).map_err(internal_error)?;
    }
    if let Some(ref s) = payload.update_sha256 {
        let t = s.trim();
        if !t.is_empty() && (t.len() != 64 || !t.chars().all(|c| c.is_ascii_hexdigit())) {
            return Err((StatusCode::BAD_REQUEST, "update_sha256 must be 64 hex chars".to_string()));
        }
        db::set_setting(&conn, "update_sha256", &t.to_lowercase()).map_err(internal_error)?;
    }
    if let Some(ref s) = payload.update_notes {
        db::set_setting(&conn, "update_notes", s.trim()).map_err(internal_error)?;
    }
    if payload.update_latest.is_some()
        || payload.update_min_supported.is_some()
        || payload.update_url.is_some()
        || payload.update_sha256.is_some()
    {
        sign_and_store_version_manifest(&conn, state.server_privkey.clone())?;
    }

    Ok(Json(json!({ "ok": true })))
}


/// Sign current update_* settings with the server key and store
/// update_signature alongside. Fail-closed: a feed without a signature
/// never verifies on the client.
fn sign_and_store_version_manifest(
    conn: &rusqlite::Connection,
    server_privkey: String,
) -> Result<(), (StatusCode, String)> {
    let get = |k: &str| -> Result<String, (StatusCode, String)> {
        db::get_setting(conn, k).map_err(internal_error).map(|v| v.unwrap_or_default())
    };
    let latest = get("update_latest")?;
    if latest.trim().is_empty() {
        return Ok(());
    }
    let sig = crate::crypto::sign_version_manifest(
        &server_privkey,
        &latest,
        &get("update_min_supported")?,
        &get("update_url")?,
        &get("update_sha256")?,
    )
    .map_err(|e| (StatusCode::INTERNAL_SERVER_ERROR, format!("sign version manifest: {e}")))?;
    db::set_setting(conn, "update_signature", &sig).map_err(internal_error)?;
    Ok(())
}

