/// Serve client application package for easy download and installation.
///
/// [Note]
/// No hardcoded release filename: the serve directories are scanned for the
/// newest file matching the DeskAgent release naming (`deskagent-*-install.exe`
/// or any `.zip`), picked by mtime. Publishing a new build is a file drop, not
/// a code change. The plain dev binary stays as a last-resort fallback and the
/// Content-Disposition keeps the real file name so the client-side upgrade
/// command can tell installer (.exe) from archive (.zip).
async fn download_client() -> Result<impl IntoResponse, (StatusCode, String)> {
    fn is_release_file(name: &str) -> bool {
        let name = name.to_lowercase();
        (name.starts_with("deskagent-") && name.ends_with("-install.exe")) || name.ends_with(".zip")
    }

    let mut candidates: Vec<(std::path::PathBuf, SystemTime)> = Vec::new();
    for dir in ["/data", "."] {
        let Ok(entries) = std::fs::read_dir(dir) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if !path.is_file() {
                continue;
            }
            let name = path
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default();
            if !is_release_file(&name) {
                continue;
            }
            let mtime = entry
                .metadata()
                .and_then(|m| m.modified())
                .unwrap_or(UNIX_EPOCH);
            candidates.push((path, mtime));
        }
    }
    // Newest release file first.
    candidates.sort_by(|a, b| b.1.cmp(&a.1));
    for path in candidates.iter().map(|(p, _)| p) {
        if let Ok(bytes) = tokio::fs::read(path).await {
            let filename = path
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_else(|| "DeskAgent-install.exe".to_owned());
            let content_type = if filename.to_lowercase().ends_with(".zip") {
                "application/zip"
            } else {
                "application/vnd.microsoft.portable-executable"
            };
            return Ok((
                [
                    (CONTENT_TYPE, content_type.to_string()),
                    (
                        CONTENT_DISPOSITION,
                        format!("attachment; filename=\"{filename}\""),
                    ),
                ],
                bytes,
            ));
        }
    }
    // Dev fallback: an unpackaged client binary next to the manager.
    for path in [
        "deskagent.exe",
        "/data/deskagent.exe",
        "../flutter/build/windows/x64/runner/Release/deskagent.exe",
    ] {
        if let Ok(bytes) = tokio::fs::read(path).await {
            let filename = std::path::Path::new(path)
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_else(|| "deskagent.exe".to_owned());
            return Ok((
                [
                    (CONTENT_TYPE, "application/vnd.microsoft.portable-executable".to_string()),
                    (
                        CONTENT_DISPOSITION,
                        format!("attachment; filename=\"{filename}\""),
                    ),
                ],
                bytes,
            ));
        }
    }
    Err((
        StatusCode::NOT_FOUND,
        "Client installer package not found on server. Please upload deskagent-*-install.exe or DeskAgent-Windows-x64.zip to server.".to_string(),
    ))
}

