/// Delivery window after a claim before the job returns to the pool.
/// The client polls every 30s, so 300s (10 ticks) is ample for a lost
/// response or a crashed client to be recovered.
const JOB_LEASE_SECS: i64 = 300;
/// Lease for jobs that carry a `silent_cmd`: the client runs it with a 15
/// minute timeout, so the lease must outlive the run (16 min) or the job
/// would be re-delivered while the client is still executing it.
const JOB_SILENT_LEASE_SECS: i64 = 960;

async fn client_jobs(
    auth: DeviceAuth,
    State(state): State<SharedState>,
    Path(id): Path<String>,
) -> Result<Json<Vec<db::JobRow>>, (StatusCode, String)> {
    if !auth.is(&id) {
        return Err((StatusCode::FORBIDDEN, "client id mismatch".to_string()));
    }
    let conn = state.db.lock().map_err(|_| db_poisoned())?;
    // Job polling doubles as a liveness heartbeat: last_seen was previously
    // only refreshed on re-register, which made "online" mean "registered in
    // the window" rather than "alive".
    db::touch_client(&conn, &id).map_err(internal_error)?;
    // Claim with a lease: 'pending' jobs AND 'running' jobs whose lease
    // expired. The claim marks them running with a fresh lease BEFORE the
    // response leaves, and the lease expiry returns lost jobs to the pool.
    let now = db::now();
    let mut jobs = db::claimable_jobs(&conn, &id, now).map_err(internal_error)?;
    for job in &jobs {
        let lease = now + if job.silent_cmd.is_empty() {
            JOB_LEASE_SECS
        } else {
            JOB_SILENT_LEASE_SECS
        };
        db::claim_job(&conn, &job.id, lease).map_err(internal_error)?;
    }
    for job in &mut jobs {
        job.status = "running".to_string();
    }
    Ok(Json(jobs))
}

async fn client_job_result(
    auth: DeviceAuth,
    State(state): State<SharedState>,
    Path((client_id, job_id)): Path<(String, String)>,
    Json(payload): Json<JobResultIn>,
) -> Result<Json<Value>, (StatusCode, String)> {
    if !auth.is(&client_id) {
        return Err((StatusCode::FORBIDDEN, "client id mismatch".to_string()));
    }
    // Only the two terminal states the daemon reports are accepted; anything
    // else would be stored verbatim into jobs.status.
    if !payload.status.eq_ignore_ascii_case("success") && !payload.status.eq_ignore_ascii_case("failed") {
        return Err((
            StatusCode::BAD_REQUEST,
            "job status must be 'success' or 'failed'".to_string(),
        ));
    }
    let conn = state.db.lock().map_err(|_| db_poisoned())?;
    // The job must exist and belong to the reporting client.
    if !db::job_owned_by(&conn, &job_id, &client_id).map_err(internal_error)? {
        return Err(not_found());
    }
    db::save_job_result(&conn, &job_id, &client_id, &payload.status, &payload.output)
        .map_err(internal_error)?;
    Ok(Json(json!({ "ok": true })))
}

/// Return all active peers in the network across all VLANs/subnets for discovery.
async fn client_get_peers(
    _auth: DeviceAuth,
    State(state): State<SharedState>,
) -> Result<Json<Value>, (StatusCode, String)> {
    let conn = state.db.lock().map_err(|_| db_poisoned())?;
    let clients = db::list_clients(&conn).map_err(internal_error)?;
    let now = db::now();
    let peers: Vec<Value> = clients
        .into_iter()
        .map(|c| {
            // Online threshold 600s, deliberately kept: it must be > the 30s
            // job-poll heartbeat by a wide margin (a laptop waking from sleep
            // or a flaky Wi-Fi link skips several polls without being gone),
            // and it matches ONLINE_WINDOW_SECS = 600 in console/index.html
            // so console and peer list never disagree.
            let online = (now - c.last_seen) <= 600;
            json!({
                "id": c.id,
                "hostname": c.hostname,
                "os": c.os,
                "os_version": c.os_version,
                "arch": c.arch,
                "ip": c.ip,
                "online": online,
                "last_seen": c.last_seen,
            })
        })
        .collect();
    Ok(Json(json!({ "peers": peers })))
}

