// ---------- chat API ----------

/// Cap for events folded into the AI context (newest first).
const AI_CONTEXT_EVENT_CAP: i64 = 20;
/// Per-event text cap in the AI context.
const AI_CONTEXT_EVENT_TEXT_CAP: usize = 200;
/// Inventory JSON cap in the AI context.
const AI_CONTEXT_INVENTORY_CAP: usize = 2500;
/// Hard cap for the whole context block (kept small: it is prepended to
/// every model call in this conversation).
const AI_CONTEXT_MAX_CHARS: usize = 6000;

fn truncate_chars(s: &str, cap: usize) -> String {
    if s.chars().count() <= cap {
        return s.to_string();
    }
    let mut out: String = s.chars().take(cap).collect();
    out.push_str("…[truncated]");
    out
}

/// Snapshot of one client's inventory + newest events for the model context.
/// Returns None when the client has neither (no point spending prompt space).
/// The DB lock is held by the caller; both reads are short synchronous queries.
fn build_ai_context(conn: &rusqlite::Connection, client_id: &str) -> Option<String> {
    let mut out = format!("[Machine context of client {client_id}]\n");
    let mut has_content = false;
    if let Ok(Some((raw, _updated_at))) = db::get_inventory(conn, client_id) {
        if !raw.trim().is_empty() {
            out.push_str(&format!(
                "Latest inventory (JSON, may be truncated): {}\n",
                truncate_chars(raw.trim(), AI_CONTEXT_INVENTORY_CAP)
            ));
            has_content = true;
        }
    }
    if let Ok(events) = db::list_events(conn, client_id, AI_CONTEXT_EVENT_CAP) {
        let events: Vec<_> = events
            .into_iter()
            .map(|e| {
                let text = truncate_chars(&e.text, AI_CONTEXT_EVENT_TEXT_CAP).replace('\n', " ");
                format!("- [{}] {} (unix {})", e.source, text, e.created_at)
            })
            .collect();
        if !events.is_empty() {
            out.push_str("Recent events (newest first):\n");
            out.push_str(&events.join("\n"));
            out.push('\n');
            has_content = true;
        }
    }
    if !has_content {
        return None;
    }
    Some(truncate_chars(&out, AI_CONTEXT_MAX_CHARS))
}

/// What the bot should do after a user message is stored.
enum BotAction {
    /// Conversation claimed by an admin — the bot stays silent.
    Skip,
    /// AI env incomplete or URL invalid at startup.
    NotConfigured,
    /// (role, content) history to send to the model.
    Ask(Vec<(String, String)>),
}

