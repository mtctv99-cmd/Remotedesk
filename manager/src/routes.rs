/// Unique id generated by a secure CSPRNG (ring::rand::SystemRandom).
fn new_id(prefix: &str) -> String {
    let rng = SystemRandom::new();
    let mut bytes = [0u8; 16];
    rng.fill(&mut bytes)
        .expect("CSPRNG failed to generate random bytes");
    let mut s = String::with_capacity(prefix.len() + 32);
    s.push_str(prefix);
    for b in bytes {
        let _ = write!(s, "{b:02x}");
    }
    s
}

