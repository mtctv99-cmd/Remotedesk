/// Active cross-VLAN probe: probe port 21118 (Direct IP) on configured subnets.
///
/// [Note]
/// Read-only by design: a responsive port does not identify a DeskAgent
/// client, so probed hosts are NEVER upserted into the clients table (that
/// used to fabricate `vlan_<ip>` "Windows/x86_64" entries which polluted the
/// client list and could be picked as deploy targets). Findings are reported
/// to the caller instead. Non-/24 subnets are reported as skipped.
async fn admin_scan_vlans(
    _auth: AdminAuth,
    State(state): State<SharedState>,
) -> Result<Json<Value>, (StatusCode, String)> {
    let subnets_str = {
        let conn = state.db.lock().map_err(|_| db_poisoned())?;
        db::get_setting(&conn, "vlan_subnets")
            .map_err(internal_error)?
            .filter(|s| !s.trim().is_empty())
            .unwrap_or_default()
    };

    let mut candidate_ips: Vec<std::net::Ipv4Addr> = Vec::new();
    let mut skipped_subnets: Vec<String> = Vec::new();
    for sub in subnets_str.split(',') {
        let sub = sub.trim();
        if sub.is_empty() {
            continue;
        }
        // Parse simple CIDRs like 192.168.1.0/24
        let mut handled = false;
        if let Some((prefix, mask_str)) = sub.split_once('/') {
            if let (Ok(base_ip), Ok(mask_len)) = (
                prefix.trim().parse::<std::net::Ipv4Addr>(),
                mask_str.trim().parse::<u8>(),
            ) {
                if mask_len == 24 {
                    let octets = base_ip.octets();
                    // Probe range .1 to .254
                    for host in 1..=254 {
                        candidate_ips.push(std::net::Ipv4Addr::new(octets[0], octets[1], octets[2], host));
                    }
                    handled = true;
                }
            }
        }
        if !handled {
            // Never silently ignore a configured range the scanner cannot use.
            skipped_subnets.push(sub.to_string());
        }
    }

    let mut found_ips: Vec<String> = Vec::new();
    // Scan concurrency using tokio tasks (batch of 64)
    for chunk in candidate_ips.chunks(64) {
        let mut set = tokio::task::JoinSet::new();
        for &ip in chunk {
            set.spawn(async move {
                let target = std::net::SocketAddr::from((ip, 21118));
                match tokio::time::timeout(
                    std::time::Duration::from_millis(350),
                    tokio::net::TcpStream::connect(target),
                )
                .await
                {
                    Ok(Ok(_stream)) => Some(ip),
                    _ => None,
                }
            });
        }

        while let Some(res) = set.join_next().await {
            if let Ok(Some(ip)) = res {
                found_ips.push(ip.to_string());
            }
        }
    }

    Ok(Json(json!({
        "ok": true,
        "scanned_ips": candidate_ips.len(),
        "found_responsive": found_ips.len(),
        "found_ips": found_ips,
        "skipped_subnets": skipped_subnets,
    })))
}

